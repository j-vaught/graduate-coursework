ax.set_ylabel('Mean squared error\n(average over 100 runs)', fontsize=11)
ax.set_title('Exercise 5.7: Off-Policy Estimation of a Blackjack State Value',
             fontsize=13, fontweight='bold', color=garnet, pad=12)
ax.set_ylim(bottom=0, top=5)
ax.set_xlim(1, NUM_EPISODES)
ax.legend(fontsize=10, frameon=True, edgecolor=black90)
ax.tick_params(labelsize=9)


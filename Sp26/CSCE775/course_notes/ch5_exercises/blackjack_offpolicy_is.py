ax.plot(episodes, ordinary_mse, color=garnet, linewidth=1.2, label='Ordinary importance sampling')
ax.plot(episodes, weighted_mse, color=horseshoe, linewidth=1.2, label='Weighted importance sampling')

ax.set_xscale('log')

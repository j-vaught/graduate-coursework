function format_project4_layout(model)
% Arrange the main diagram and route each signal for readability.
blocks={'Base disturbance',[90 245 195 285];'Cart force',[275 250 305 280]; ...
 'Nonlinear plant',[385 205 515 325];'State dimensions',[565 225 595 255]; ...
 'MPC Controller',[660 195 745 315];'Actuator limit',[800 245 850 285]; ...
 'Upright reference',[525 350 615 380];'Command log',[900 245 1015 285]; ...
 'Optimizer status',[800 355 920 385];'Disturbance log',[205 445 315 485]; ...
 'Total force log',[365 445 475 485];'State log',[560 445 670 485]};
lines=find_system(model,'FindAll','on','SearchDepth',1,'Type','line');
for i=1:numel(lines)
    try, delete_line(lines(i)); catch, end
end
for i=1:size(blocks,1), set_param([model '/' blocks{i,1}],'Position',blocks{i,2}); end
set_param([model '/State dimensions'],'ShowName','off');
edges={'Base disturbance/1','Cart force/2';'Base disturbance/1','Disturbance log/1'; ...
 'Cart force/1','Nonlinear plant/1';'Cart force/1','Total force log/1'; ...
 'Nonlinear plant/1','State dimensions/1';'Nonlinear plant/1','State log/1'; ...
 'State dimensions/1','MPC Controller/1';'Upright reference/1','MPC Controller/2'; ...
 'MPC Controller/1','Actuator limit/1';'MPC Controller/2','Optimizer status/1'; ...
 'Actuator limit/1','Cart force/1';'Actuator limit/1','Command log/1'};
for i=1:size(edges,1), add_line(model,edges{i,1},edges{i,2},'autorouting','on'); end
end
